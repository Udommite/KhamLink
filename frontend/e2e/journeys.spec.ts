test('VAL-008/032/047/049/059 empty, model failure, stale and privacy', async ({ page }) => {
  await page.goto('/#/word/%E0%A4%A')
  await expect(page.getByRole('alert')).toContainText('ไม่พบคำนี้')
  await page.goto('/')
  await page.getByRole('link', { name: 'ข้ามไปเนื้อหาหลัก' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toBeFocused()
  expect(new URL(page.url()).hash).not.toBe('#main')
  await page.getByLabel('คำ ความหมาย หรือสิ่งที่คุณอยากสื่อ').fill('zzzzzqqqqqxxxx')
  await page.getByRole('button', { name: 'ค้นหาคำ', exact: false }).first().click()
  await expect(page.locator('.empty-state')).toContainText('ยังไม่พบคำที่มั่นใจได้')
  await page.goto('/#/word/w_stale')
  await expect(page.getByRole('alert')).toContainText('ไม่พบคำนี้')
  await page.goto('/#/word/' + encodeURIComponent('อนุรักษ์'))
  await expect(page.getByTestId('source-content')).toBeVisible()
  await page.route('**/api/explanations', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ data: null, meta: { correlation_id: 'test' }, error: { code: 'UNAVAILABLE', message: 'คำอธิบายไม่พร้อม กรุณาลองอีกครั้ง' } }) }))
  await page.getByRole('button', { name: /ช่วยอธิบายคำนี้/ }).click()
  await expect(page.getByRole('alert')).toContainText('คำอธิบายไม่พร้อม')
  await expect(page.getByTestId('source-content')).toContainText('รักษาให้คงเดิม')
  await page.getByRole('button', { name: 'ข้อมูลและความเป็นส่วนตัว' }).click()
  await expect(page.getByRole('dialog')).toContainText('ไม่มีคุกกี้ติดตาม')
  await accessible(page)
})

test('VAL-023/024/025/026/038 map and list have the same sourced edges', async ({ page, request }) => {
  const response = await request.get('/api/words/' + encodeURIComponent('ศูนย์') + '/related')
  // Use a real explicit cross-reference if present in the corpus; otherwise inspect real sparse behavior.
  const map = response.ok() ? (await response.json()).data : null
  await page.goto('/#/word/' + encodeURIComponent('ศูนย์'))
  if (map?.relationships.length) {
    await expect(page.locator('.relation-list li')).toHaveCount(map.relationships.length)
    await expect(page.getByRole('img', { name: /แผนที่คำ/ })).toBeVisible()
    await accessible(page)
    await page.locator('.relation-list li').first().getByRole('link').click()
    await expect(page.getByRole('heading', { name: map.relationships[0].word, exact: true })).toBeVisible()
  } else {
    await page.goto('/#/word/' + encodeURIComponent('อนุรักษ์'))
    await expect(page.locator('.empty-map')).toContainText('ยังไม่มีข้อมูลคำที่เกี่ยวข้อง')
    await accessible(page)
  }
})
