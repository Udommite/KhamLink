import { test, expect, Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function accessible(page: Page) {
  const report = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(report.violations, JSON.stringify(report.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })))).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
}

async function capture(page: Page, path: string) {
  // Capture from scroll origin: Chromium otherwise composites off-screen fixed
  // skip links into full-page images at the previous scroll offset.
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path, fullPage: true })
}

